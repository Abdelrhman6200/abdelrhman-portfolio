/*
 * Generates client/src/content/colophon.ts — the site's own spec sheet.
 *
 * A portfolio arguing that claims should be checkable ought to state its own
 * numbers, and get them from the repository rather than from memory. Every
 * figure here is counted at build time, so the colophon cannot drift the way a
 * hand-written "built with React" line does.
 *
 * Runs as part of `npm run build`, alongside the sitemap.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { execSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === "node_modules" ? [] : walk(full);
    return [full];
  });
}

const src = join(root, "client", "src");
const files = walk(src);

const testFiles = files.filter((file) => /.test.tsx?$/.test(file));

/**
 * The true count comes from vitest, not from counting `it(` calls: `it.each`
 * and `describe.each` declare one block and run many, so a static count
 * understates this suite by about a third. A colophon that misreports the site
 * is worse than no colophon.
 */
function countTests() {
  try {
    // execSync with one command string: passing an args array with shell:true
    // is deprecated, and npx needs a shell on Windows.
    const output = execSync("npx vitest run --reporter=json", {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 32 * 1024 * 1024,
    });
    const parsed = JSON.parse(output.slice(output.indexOf("{")));
    if (typeof parsed.numTotalTests === "number") return parsed.numTotalTests;
  } catch {
    // Vitest unavailable, or the suite failed. Fall back rather than blocking
    // a build; CI runs the suite separately and will fail there properly.
  }
  return null;
}

const tests = countTests();

const sourceFiles = files.filter((file) => /\.(tsx?|css)$/.test(file) && !/\.test\./.test(file));
const lines = sourceFiles
  .map((file) => readFileSync(file, "utf8").split("\n").length)
  .reduce((sum, count) => sum + count, 0);

/** Bundle size from the previous build, when one exists. */
let bundleKb = null;
try {
  const assets = join(root, "dist", "assets");
  const total = readdirSync(assets)
    .filter((name) => /\.(js|css)$/.test(name))
    .map((name) => statSync(join(assets, name)).size)
    .reduce((sum, size) => sum + size, 0);
  bundleKb = Math.round(total / 1024);
} catch {
  // First build in a clean checkout — the field is simply omitted.
}

const colophon = {
  dependencies: Object.keys(pkg.dependencies ?? {}).length,
  tests,
  testFiles: testFiles.length,
  sourceFiles: sourceFiles.length,
  lines,
  bundleKb,
  stack: ["React", "TypeScript", "Vite", "wouter"],
};

writeFileSync(
  join(src, "content", "colophon.ts"),
  `/*
 * GENERATED by scripts/colophon.mjs — do not edit by hand.
 *
 * Counted from this repository at build time, so the site's statements about
 * itself cannot drift from what it actually is.
 */
export const colophon = ${JSON.stringify(colophon, null, 2)} as const;
`
);

console.log(
  `colophon: ${colophon.dependencies} deps, ${colophon.tests} tests, ` +
    `${colophon.sourceFiles} files, ${colophon.lines} lines`
);
